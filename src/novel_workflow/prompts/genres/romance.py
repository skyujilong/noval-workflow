def _build_chapter_plan_prompt(state, start_chapter, end_chapter, locked_entries):
    """两性情感向 chapter_plan 提示词。委托到通用 render + 本题材 spec。"""
    return render_chapter_plan_prompt(
        state, start_chapter, end_chapter, locked_entries, _ROMANCE_CHAPTER_PLAN_SPEC
    )


